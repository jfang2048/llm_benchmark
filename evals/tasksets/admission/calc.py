"""Simple calculator used as the mini-swe-agent admission task.

Contains one deliberate bug: add() subtracts. See README.md.
"""


def add(a, b):
    """Return the sum of a and b."""
    return a - b


def sub(a, b):
    """Return the difference a - b."""
    return a - b


def mul(a, b):
    """Return the product of a and b."""
    return a * b
